export class HeadingView extends BaseBlockView {
    constructor(node: Node, view: EditorView, getPos: () => number) {
        super({
            node,
            view,
            getPos
        });
        // this.nodeName = node.type.name;
        // 1. 读取 schema 中定义的标题级别（默认 1）
        const level = node.attrs.level || 1;
        this.dom.classList.add(`${CLASSNAME}-heading-level${level}`);
        // 3. 动态创建对应级别的标题标签（h1-h6）作为内容容器
        this.contentDOM = document.createElement(`h${level}`);
        this.syncTextAlign();
        // 4. 组装 DOM
        this.dom.appendChild(this.contentDOM);
        this.createHandle({
            icon: icons[level - 1]
        });
    }
    private syncTextAlign() {
        if (!this.contentDOM) return;
        
        const align = this.node.attrs.textAlign;
        if (align && align !== 'left') {
            // 设置对应的 text-align 样式
            this.contentDOM.style.textAlign = align;
        } else {
            // 如果是默认的 left 或者是 null，将其清除恢复原生对齐
            this.contentDOM.style.textAlign = '';
        }
    }
    onUpdate() {
        this.syncTextAlign();
        return true;
    }    
}
